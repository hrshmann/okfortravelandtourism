<?php
declare(strict_types=1);

/**
 * One-time web installer. Writes app/config.php, creates the tables, loads starter content
 * and the first administrator. Once config.php exists the installer is permanently disabled.
 */
route('GET|POST', '/install', function () {
    if (is_installed()) {
        redirect('/admin');
    }
    session_boot();
    $checks = install_checks();
    $errors = [];
    $values = [
        'driver' => extension_loaded('pdo_mysql') ? 'mysql' : 'sqlite',
        'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
        'site_name' => 'OK Travel & Tourism', 'whatsapp' => '', 'admin_name' => '', 'admin_email' => '', 'timezone' => 'Asia/Dubai',
    ];
    if (is_post()) {
        csrf_check();
        foreach ($values as $k => $_) {
            $values[$k] = trim((string) ($_POST[$k] ?? ''));
        }
        $password = (string) ($_POST['admin_password'] ?? '');
        $required = array_filter($checks, fn($c) => empty($c['optional']));
        if (in_array(false, array_column($required, 'ok'), true)) $errors[] = 'Fix the server requirements marked in red first.';
        if (!filter_var($values['admin_email'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid administrator email.';
        if ($values['admin_name'] === '') $errors[] = 'Enter the administrator’s name.';
        if ($p = password_problem($password)) $errors[] = $p;
        if (!in_array($values['timezone'], timezone_identifiers_list(), true)) $values['timezone'] = 'Asia/Dubai';

        $db = $values['driver'] === 'sqlite'
            ? ['driver' => 'sqlite', 'path' => 'storage/database.sqlite']
            : ['driver' => 'mysql', 'host' => $values['db_host'], 'port' => (int) $values['db_port'], 'name' => $values['db_name'], 'user' => $values['db_user'], 'pass' => (string) ($_POST['db_pass'] ?? '')];

        if (!$errors) {
            try {
                $pdo = db_connect($db);
                db_use($pdo);
                if ((int) val("SELECT COUNT(*) FROM " . ($db['driver'] === 'sqlite' ? "sqlite_master WHERE type='table' AND name='users'" : "information_schema.tables WHERE table_schema = DATABASE() AND table_name = 'users'"))) {
                    if ((int) val('SELECT COUNT(*) FROM users')) {
                        throw new RuntimeException('This database already contains an installation. Use an empty database, or restore app/config.php from your backup.');
                    }
                }
            } catch (PDOException $e) {
                $errors[] = 'Could not connect to the database: ' . $e->getMessage();
            } catch (RuntimeException $e) {
                $errors[] = $e->getMessage();
            }
        }

        if (!$errors) {
            require_once APP . '/lib/seed.php';
            date_default_timezone_set($values['timezone']);
            $pdo->beginTransaction();
            try {
                schema_install($pdo);
                // MySQL commits implicitly after CREATE TABLE; start a fresh transaction for the data.
                if (!$pdo->inTransaction()) {
                    $pdo->beginTransaction();
                }
                seed_content();
                $settings = [
                    'site_name' => $values['site_name'] ?: 'OK Travel & Tourism',
                    'timezone' => $values['timezone'],
                    'notify_email' => $values['admin_email'],
                    'schema_version' => (string) SCHEMA_VERSION,
                ];
                if ($values['whatsapp'] !== '') {
                    $settings['whatsapp'] = preg_replace('/\D/', '', $values['whatsapp']);
                }
                settings_save($settings);
                insert('users', [
                    'name' => $values['admin_name'], 'email' => mb_strtolower($values['admin_email']),
                    'password_hash' => password_hash($password, PASSWORD_DEFAULT), 'role' => 'admin', 'active' => 1,
                    'created_at' => now(), 'updated_at' => now(),
                ]);
                if ($pdo->inTransaction()) {
                    $pdo->commit();
                }
            } catch (Throwable $e) {
                if ($pdo->inTransaction()) {
                    $pdo->rollBack();
                }
                $errors[] = 'Installation failed: ' . $e->getMessage();
            }
        }

        if (!$errors) {
            $config = [
                'app_key' => bin2hex(random_bytes(32)),
                'db' => $db,
                'timezone' => $values['timezone'],
                'debug' => false,
                'installed_at' => date('c'),
            ];
            $php = "<?php\n// Generated by the installer on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export($config, true) . ";\n";
            if (@file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) {
                $errors[] = 'Could not write app/config.php. Make the app folder writable (755) and try again.';
            } else {
                @chmod(CONFIG_FILE, 0640);
                $GLOBALS['CONFIG'] = $config;
                $u = row('SELECT * FROM users WHERE email = ?', [mb_strtolower($values['admin_email'])]);
                login_user($u);
                flash('success', 'Your website is installed. Start with Settings to add your real contact details.');
                redirect('/admin');
            }
        }
    }
    echo render('admin/install', compact('checks', 'errors', 'values'));
});

function install_checks(): array
{
    $writable = fn($p) => is_dir($p) ? is_writable($p) : @mkdir($p, 0755, true);
    return [
        ['label' => 'PHP 8.0 or newer (you have ' . PHP_VERSION . ')', 'ok' => PHP_VERSION_ID >= 80000],
        ['label' => 'PDO MySQL or SQLite driver', 'ok' => extension_loaded('pdo_mysql') || extension_loaded('pdo_sqlite')],
        ['label' => 'mbstring extension', 'ok' => extension_loaded('mbstring')],
        ['label' => 'GD extension (image resizing)', 'ok' => extension_loaded('gd'), 'optional' => true],
        ['label' => 'cURL extension (live flight fares)', 'ok' => extension_loaded('curl'), 'optional' => true],
        ['label' => 'app/ folder is writable', 'ok' => is_writable(APP)],
        ['label' => 'storage/ folder is writable', 'ok' => $writable(STORAGE)],
        ['label' => 'uploads/ folder is writable', 'ok' => $writable(UPLOADS)],
    ];
}
